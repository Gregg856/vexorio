'use strict';
const assert=require('node:assert/strict');
const {summarizeRX}=require('../rx-queen-computer-status.cjs');
const {runCloudComputer}=require('../rx-mega-cloud-computer.cjs');
const p=summarizeRX(runCloudComputer());
assert.equal(p.state,'pending');
assert.equal(p.cloudServerProvisioned,false);
assert.equal(p.totalTestDurationMs,0);
assert.deepEqual(p.slowestChecks,[]);
const failed=summarizeRX({schema:1,kind:'rx-mega-cloud-computer',checks:[{file:'tests/x.cjs',status:'failed'}],labs:{}});
assert.equal(failed.state,'needs_attention');
const timed=summarizeRX({schema:1,kind:'rx-mega-cloud-computer',checks:[{file:'a',status:'passed',durationMs:40},{file:'b',status:'passed',durationMs:90},{file:'c',status:'passed',durationMs:3}],labs:{}});
assert.equal(timed.totalTestDurationMs,133);
assert.deepEqual(timed.slowestChecks.map(x=>x.file),['b','a','c']);
assert.equal(failed.issues[0].priority,'high');
assert.throws(()=>summarizeRX({checks:[]}),/Invalid RX report/);
const ants=summarizeRX({schema:1,kind:'rx-cosmos-ant-check-report',checks:[{file:'tests/rx-ai-core.cjs',status:'passed'}],queueTasks:3,approvedTasks:1,skippedTasks:2,executed:1,labs:{}});
assert.equal(ants.state,'checks_passed');
assert.deepEqual(ants.antQueue,{queued:3,approved:1,skipped:2,executed:1,approvalRequired:true});
assert.equal(p.antQueue,null);
console.log('PASS RX QUEEN status summarizes reports without claiming real cloud VM');
