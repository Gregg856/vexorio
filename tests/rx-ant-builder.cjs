'use strict';
const assert=require('node:assert/strict');
const {prepareBuildQueue,draftTestSpecification,generateRegressionTestDraft,generatePatchProposal,prepareTaskPatchPreview,suggestTaskPatch}=require('../rx-ant-builder.cjs');
const task={source:'RX FAST',target:'rx-photo-motion.js',action:'Investigate empty video export',priority:'high',recurrent:true,historyOccurrences:3};
const result=prepareBuildQueue({kind:'rx-ant-task-board',tasks:[task,{...task,target:'other.js',recurrent:false}]});
assert.equal(result.total,1);
assert.equal(result.queue[0].testDraft.kind,'test-specification');
assert.equal(result.queue[0].testDraft.testCodeGenerated,false);
assert.equal(result.queue[0].requiresApproval,true);
assert.equal(result.autoChangesApplied,0);
assert.equal(prepareBuildQueue({kind:'rx-ant-task-board',tasks:[]}).total,0);
assert.throws(()=>prepareBuildQueue({kind:'bad',tasks:[]}),/Invalid/);
assert.ok(!draftTestSpecification({...task,target:'test\\nmalicious'}).title.includes('\n'));
const draft=generateRegressionTestDraft({target:'rx-photo-motion.js',request:'Investigate empty export'});
assert.ok(draft.source.includes('test.skip('));
assert.ok(draft.source.includes(String.fromCharCode(10)));
assert.doesNotThrow(()=>new (require('node:vm').Script)(draft.source));
assert.equal(draft.requiresApproval,true);
assert.equal(draft.status,'draft_requires_implementation');
const injection=generateRegressionTestDraft({target:"x');process.exit(1);//",request:'hello\\n});process.exit(1);//'});
assert.doesNotThrow(()=>new (require('node:vm').Script)(injection.source));
assert.equal(injection.source.includes('process.exit(1)'),false,'Untrusted task text must not become executable code');
const proposal=generatePatchProposal({target:'rx-photo-motion.js',request:'empty export'});
assert.equal(proposal.codeChangesGenerated,false);
assert.equal(proposal.diff,null);
assert.equal(proposal.requiresApproval,true);
assert.equal(result.queue[0].patchProposal.kind,'patch-proposal');
const patchPreview=prepareTaskPatchPreview(task,'const speed=1;', {oldText:'speed=1',newText:'speed=2'});
assert.equal(patchPreview.preview.preview,'const speed=2;');
assert.equal(patchPreview.requiresApproval,true);
assert.equal(patchPreview.proposal.applied,false);
assert.throws(()=>prepareTaskPatchPreview(task,'const speed=3;', {oldText:'speed=1',newText:'speed=2'}),/missing or ambiguous/);
const suggested=suggestTaskPatch({target:'src/example.js',action:'remove debugger statement'},'const x=1;\ndebugger;');
assert.equal(suggested.status,'review_only');
assert.equal(suggested.preview.preview,'const x=1;\n');
assert.equal(suggested.applied,false);
assert.equal(suggested.requiresApproval,true);
assert.equal(suggestTaskPatch({target:'src/example.js',action:'fix unknown bug'},'debugger;').status,'unsupported_rule');
assert.equal(suggestTaskPatch({target:'src/example.js',action:'remove debugger'},'debugger;\ndebugger;').status,'manual_review_required');
console.log('PASS RX ANT BUILDER draft-only safety');
