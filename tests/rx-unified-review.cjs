'use strict';
const assert=require('node:assert/strict');
const {reviewRX}=require('../rx-unified-review.cjs');
const supervisor={kind:'rx-queen-ant-supervisor',issues:[{source:'fast',action:'inspect_failed_test',target:'src/example.js',priority:'high'}]};
const sources={'src/example.js':'const x=1;\ndebugger;\n'};
const first=reviewRX({supervisor,runId:'run-1',sources});
assert.equal(first.kind,'rx-unified-review');
assert.equal(first.board.tasks.length,1);
assert.equal(first.builder.total,0);
assert.equal(first.reviews.length,1);
assert.equal(first.reviews[0].review.suggestions.length,1);
assert.equal(first.productionModified,false);
const second=reviewRX({supervisor,previousMemory:first.memory,previousQueue:first.reviewQueue,runId:'run-2',sources});
assert.equal(second.board.tasks[0].recurrent,true);
assert.equal(second.builder.total,1);
assert.equal(second.builder.queue[0].requiresApproval,true);
assert.equal(second.autoFixesApplied,0);
assert.equal(first.reviewQueue.tasks[0].occurrences,1);
assert.equal(second.reviewQueue.tasks[0].occurrences,2);
assert.equal(second.reviewQueue.tasks[0].firstSeen,'run-1');
assert.equal(second.reviewQueue.tasks[0].status,'awaiting_review');
assert.equal(second.reviewQueue.tasks[0].approved,false);
assert.equal(second.reviewQueue.tasks[0].executed,false);
assert.equal(second.reviewQueue.executions,0);
assert.equal(second.reviewQueue.productionModified,false);
assert.throws(()=>reviewRX({supervisor,runId:'../bad',sources}),/Invalid RX run ID/);
console.log('PASS RX unified Queen Medusa Memory Ant Developer pipeline');
