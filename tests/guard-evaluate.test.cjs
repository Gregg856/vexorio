'use strict';
const assert=require('node:assert/strict');
const {evaluateListing}=require('../guard/evaluate.cjs');
const listing={title:'Rower miejski',description:'Sprzedam sprawny rower, odbiór osobisty.'};
const clean=evaluateListing(listing);
assert.equal(clean.mode,'advisory');
assert.equal(clean.decision,'none');
assert.equal(clean.requiresHumanReview,false);
const withImage=evaluateListing(listing,{images:[{mime:'image/jpeg',size:1024}]});
assert.equal(withImage.requiresHumanReview,true);
assert.equal(withImage.images[0].classification,'unknown');
assert.ok(withImage.flags.includes('visual_review_required'));
const duplicate=evaluateListing(listing,{similarListings:[{title:'Miejski rower',description:'Osobisty odbiór, sprawny rower sprzedam.'}]});
assert.ok(duplicate.flags.includes('possible_duplicate'));
assert.equal(duplicate.decision,'none');
const suspicious=evaluateListing({title:'Oferta',description:'Send your password and pay outside using gift card.'});
assert.equal(suspicious.requiresHumanReview,true);
assert.equal(suspicious.decision,'none');
assert.ok(evaluateListing(listing,{images:null}).flags.includes('invalid_image_list'));
console.log('PASS: Guard advisory reports do not publish, reject, mutate or store listings');
