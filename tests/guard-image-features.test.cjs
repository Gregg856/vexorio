'use strict';
const assert=require('node:assert/strict');
const {inspectImageBytes}=require('../guard/image-features.cjs');
const png=Uint8Array.from([137,80,78,71,13,10,26,10,0,0,0,13,73,72,68,82,0,0,0,2,0,0,0,3]);
const result=inspectImageBytes(png,'image/png');
assert.equal(result.classification,'unknown');
assert.equal(result.status,'review');
assert.equal(result.metadata.width,2);
assert.equal(result.metadata.height,3);
assert.deepEqual(result.signals,['visual_review_required']);
assert.deepEqual(inspectImageBytes(png,'image/jpeg').signals,['mime_signature_mismatch']);
assert.deepEqual(inspectImageBytes(Uint8Array.from([1,2,3]),'image/png').signals,['unrecognized_image_signature']);
assert.deepEqual(inspectImageBytes(null,'image/png').signals,['invalid_image_bytes']);
const vp8x=Uint8Array.from([82,73,70,70,22,0,0,0,87,69,66,80,86,80,56,88,10,0,0,0,0,0,0,0,99,0,0,49,0,0]);
const extended=inspectImageBytes(vp8x,'image/webp');
assert.equal(extended.metadata.width,100);
assert.equal(extended.metadata.height,50);
const vp8=Uint8Array.from([82,73,70,70,22,0,0,0,87,69,66,80,86,80,56,32,10,0,0,0,0,0,0,157,1,42,100,0,50,0]);
const lossy=inspectImageBytes(vp8,'image/webp');
assert.equal(lossy.metadata.width,100);
assert.equal(lossy.metadata.height,50);
const vp8l=Uint8Array.from([82,73,70,70,17,0,0,0,87,69,66,80,86,80,56,76,5,0,0,0,47,99,64,12,0]);
const lossless=inspectImageBytes(vp8l,'image/webp');
assert.equal(lossless.metadata.width,100);
assert.equal(lossless.metadata.height,50);
console.log('PASS: Guard offline image header inspection, mismatch detection and mandatory review');
