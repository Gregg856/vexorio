'use strict';
const assert=require('node:assert/strict');
const {createRXHearts}=require('../rx-million-hearts.js');
const {reviewModelCandidate}=require('../rx-neuron-v2.js');
const rx=createRXHearts();
assert.equal(reviewModelCandidate(rx).status,'blocked');
rx.rememberFailure('tests','overflow');
rx.rememberVerifiedFix('tests','overflow','fix_01',{testsPassed:true});
const noEval=reviewModelCandidate(rx);
assert.equal(noEval.datasetSummary.candidateExamples,1);
assert.equal(noEval.status,'blocked');
const examples=Array.from({length:10},()=>({expectedFixId:'fix_01',approvedForEvaluation:true}));
const evaluation={examples,baselinePredictions:Array(10).fill('wrong'),candidatePredictions:Array(10).fill('fix_01')};
const approved=reviewModelCandidate(rx,{evaluation});
assert.equal(approved.status,'ready_for_human_review');
assert.equal(approved.requiresHumanApproval,true);
assert.equal(approved.mayTrain,false);
assert.equal(approved.mayDeploy,false);
const failed=reviewModelCandidate(rx,{evaluation:{...evaluation,candidatePredictions:Array(10).fill('wrong')}});
assert.equal(failed.status,'blocked');
console.log('RX NEURON 2.0: PASS');
