'use strict';
const assert=require('node:assert/strict');
const {RXMillionHearts,createRXHearts}=require('../rx-million-hearts.js');
(async()=>{
 const rx=createRXHearts();
 assert.equal(rx.snapshot().registeredCells,10);
 assert.equal(rx.rememberFailure('tests','mobile_overflow'),1);
 assert.equal(rx.snapshot().recurringFailures.length,0);
 assert.equal(rx.rememberFailure('tests','mobile_overflow'),2);
 assert.deepEqual(rx.snapshot().recurringFailures,[{cell:'tests',code:'mobile_overflow',count:2}]);
 assert.throws(()=>rx.rememberFailure('tests','secret=abc'),/Invalid failure code/);
 assert.equal(rx.suggestKnownFix('tests','mobile_overflow'),null);
 assert.throws(()=>rx.rememberVerifiedFix('tests','mobile_overflow','fix_001'),/Verified tests required/);
 assert.equal(rx.rememberVerifiedFix('tests','mobile_overflow','fix_001',{testsPassed:true}).verifiedFix,'fix_001');
 assert.deepEqual(rx.suggestKnownFix('tests','mobile_overflow'),{cell:'tests',code:'mobile_overflow',fixId:'fix_001',requiresApproval:true});
 assert.throws(()=>rx.rememberVerifiedFix('tests','mobile_overflow','../unsafe',{testsPassed:true}),/Invalid fix ID/);

 const limitedMemory=new RXMillionHearts({memoryLimit:1});
 limitedMemory.register('tests',async()=>true);
 limitedMemory.rememberFailure('tests','first');
 limitedMemory.rememberFailure('tests','second');
 assert.equal(limitedMemory.failurePatterns.size,1);

 assert.equal(rx.snapshot().logicalHeads,1000);
 const million=new RXMillionHearts({logicalHeads:1000000,maxConcurrent:2,maxQueue:3});
 assert.equal(million.snapshot().logicalHeads,1000000);
 assert.equal(million.headId(0),'RX-000001');
 assert.equal(million.headId(999999),'RX-1000000');
 assert.throws(()=>million.headId(1000000),/Invalid logical head/);
 assert.equal(million.snapshot().active,0);
 assert.equal(million.snapshot().queued,0);

 assert.equal((await rx.dispatch('tests',{id:1})).status,'needs-integration');
 const bounded=new RXMillionHearts({maxConcurrent:1,maxQueue:1});
 let release;
 bounded.register('slow',()=>new Promise(resolve=>{release=resolve;}));
 const first=bounded.dispatch('slow');
 await Promise.resolve();await Promise.resolve();
 const second=bounded.dispatch('slow');
 await assert.rejects(bounded.dispatch('slow'),/queue full/);
 release('one');assert.equal(await first,'one');
 await Promise.resolve();await Promise.resolve();
 release('two');assert.equal(await second,'two');
 assert.equal(bounded.snapshot().stats.completed,2);
 const queen=new RXMillionHearts({maxConcurrent:1,maxQueue:4});
 let unblock;
 const order=[];
 queen.register('work',async name=>{order.push(name);if(name==='first')await new Promise(resolve=>{unblock=resolve;});return name;});
 const a=queen.dispatch('work','first');
 await Promise.resolve();await Promise.resolve();
 const low=queen.dispatch('work','low',{priority:0});
 const urgent=queen.dispatch('work','urgent',{priority:9});
 const equal=queen.dispatch('work','equal',{priority:9});
 assert.equal(queen.snapshot().urgentQueued,2);
 await assert.rejects(queen.dispatch('work','invalid',{priority:10}),/Priority/);
 unblock();
 assert.deepEqual(await Promise.all([a,low,urgent,equal]),['first','low','urgent','equal']);
 assert.deepEqual(order,['first','urgent','equal','low']);
 assert.equal(queen.snapshot().active,0);
 const watch=new RXMillionHearts({maxConcurrent:1});
 let finish;
 watch.register('slow',()=>new Promise(resolve=>{finish=resolve;}));
 const pending=watch.dispatch('slow');
 await Promise.resolve();await Promise.resolve();
 assert.equal(watch.snapshot().active,1);
 assert.equal(watch.stalledJobs(1).length<=1,true);
 assert.throws(()=>watch.stalledJobs(0),/Invalid stall threshold/);
 finish('done');
 assert.equal(await pending,'done');
 await Promise.resolve();await Promise.resolve();
 assert.equal(watch.stalledJobs(1).length,0);

 console.log('RX MILION SERC 1.0: PASS');
})().catch(err=>{console.error(err);process.exitCode=1;});
