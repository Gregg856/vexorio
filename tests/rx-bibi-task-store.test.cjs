'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {readTasks,saveTasks,proposeStatusChange,applyApprovedChange,findSimilarTasks}=require('../rx-bibi-task-store.cjs');
const {chatRX}=require('../rx-brain-chat-engine.cjs');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'rx-bibi-store-'));
try{
 const file=path.join(dir,'tasks.json');
 assert.deepEqual(readTasks(file),[]);
 const tasks=[{title:'Naprawa czatu Android',status:'completed'},{title:'Test panelu',status:'pending'}];
 assert.equal(saveTasks(file,tasks),2);
 assert.deepEqual(readTasks(file),tasks);
 const response=chatRX('Co już zrobione?',{tasks:readTasks(file)});
 assert.match(response.answer,/Naprawa czatu Android/);
 assert.doesNotMatch(response.answer,/Test panelu/);
 assert.equal(response.completedCount,1);
 assert.equal(response.executed,0);
 assert.throws(()=>saveTasks(file,[{title:'Zadanie',status:'verified'}]),/Invalid tasks/);
 assert.deepEqual(readTasks(file),tasks);
 const proposal=proposeStatusChange(tasks,'Test panelu','completed');
 assert.equal(proposal.previousStatus,'pending');
 assert.throws(()=>applyApprovedChange(file,proposal),/Explicit approval required/);
 assert.deepEqual(readTasks(file),tasks);
 const approved=applyApprovedChange(file,proposal,{approved:true});
 assert.equal(approved[1].status,'completed');
 assert.equal(readTasks(file)[1].status,'completed');
 assert.throws(()=>applyApprovedChange(file,proposal,{approved:true}),/Stale proposal/);
 assert.throws(()=>proposeStatusChange(tasks,'Nie istnieje','completed'),/exactly one/);
 assert.throws(()=>proposeStatusChange(tasks,'Naprawa czatu Android','completed'),/already has requested status/);
 assert.throws(()=>proposeStatusChange(tasks,'Naprawa czatu Android','pending'),/cannot be reopened/);
 assert.throws(()=>proposeStatusChange(readTasks(file),'Test panelu','completed'),/already has requested status/);
 assert.throws(()=>applyApprovedChange(file,{title:'Test panelu',index:1,previousStatus:'completed',status:'pending'},{approved:true}),/Unsafe status transition/);
 assert.equal(readTasks(file)[1].status,'completed');

 assert.equal(findSimilarTasks(tasks,'  NAPRAWA   CZATU android  ').length,1);
 assert.equal(findSimilarTasks(tasks,'Naprawa czatu i płatności').length,0);
 assert.throws(()=>proposeStatusChange([{title:'Naprawa czatu Android',status:'pending'},{title:'naprawa  CZATU android',status:'pending'}],'NAPRAWA CZATU ANDROID','completed'),/exactly one/);
 assert.equal(proposeStatusChange(tasks,'  TEST   PANELU  ','completed').index,1);
 fs.writeFileSync(file,'{broken json');
 assert.throws(()=>readTasks(file),SyntaxError);
 console.log('RX BIBI level 7: persistence, reload, validation and corrupt file tests passed');
}finally{fs.rmSync(dir,{recursive:true,force:true});}
