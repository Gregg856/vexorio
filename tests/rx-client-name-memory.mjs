import assert from 'node:assert/strict';
import {planRXChat} from '../rx-chat-planner.mjs';
const first='Cześć BIBI! Mam na imię Marek. Jak się dzisiaj czujesz?';
const answer1=planRXChat(first).answer;
assert.match(answer1,/Marek/);
assert.doesNotMatch(answer1,/Rozumiem, że chcesz porozmawiać o tym temacie/);
const second='BIBI, pamiętasz, jak mam na imię? Powiedz też, o czym przed chwilą rozmawialiśmy.';
const answer2=planRXChat(second,[first,answer1]).answer;
assert.match(answer2,/Marek/);
assert.match(answer2,/Wcześniej napisałeś/);
assert.match(planRXChat('Jak mam na imię?').answer,/Nie podałeś/);
assert.match(planRXChat('Co o mnie wiesz?', [first,answer1]).answer,/Marek/);
assert.match(planRXChat('Co wiesz o mnie?').answer,/Nie mam jeszcze/);
assert.doesNotMatch(planRXChat('Co o mnie wiesz?', [first,answer1]).answer,/mieszkasz|pracujesz|lat/);
const profile='Mieszkam w Krakowie. Interesuję się astronomią. Lubię książki.';
const profileAnswer=planRXChat('Co o mnie wiesz?', [first,answer1,profile,'Dzięki.']).answer;
assert.match(profileAnswer,/Krakowie/);
assert.match(profileAnswer,/astronomią/);
assert.doesNotMatch(profileAnswer,/Interesujesz się astronomią i lubię książki/);
assert.match(profileAnswer,/książki/);
assert.doesNotMatch(planRXChat('Co o mnie wiesz?').answer,/Krakowie|astronomią|książki/);
const changedCity=planRXChat('Co o mnie wiesz?', [first,answer1,'Mieszkam w Krakowie.','Rozumiem.','Przeprowadziłem się z Krakowa do Warszawy.','Powodzenia!']).answer;
assert.match(changedCity,/miasto: Warszawy/);
assert.doesNotMatch(changedCity,/miasto: Krakowie/);
const sameTurn=planRXChat('Przeprowadziłem się z Krakowa do Warszawy. BIBI, co teraz o mnie wiesz?').answer;
assert.match(sameTurn,/miasto: Warszawy/);
assert.doesNotMatch(sameTurn,/RX Coordinator|Mrówek/);
assert.match(planRXChat('Mam na imię Ola. Co o mnie wiesz?').answer,/Masz na imię Ola/);
assert.match(planRXChat('Nazywam się Ewa. Co teraz o mnie wiesz?').answer,/Masz na imię Ewa/);
assert.match(planRXChat('Mam na imię Kasia.').answer,/O czym masz ochotę porozmawiać/);
assert.doesNotMatch(planRXChat('Mam na imię Kasia.').answer,/Dzięki, że pytasz/);
assert.match(planRXChat('Mam na imię Kasia. Jak się czujesz?').answer,/Dzięki, że pytasz/);
const historyWithRecall=['Lubię astronomię.','Świetnie!','Przypomnij, o czym przed chwilą rozmawialiśmy.','Rozmawialiśmy o astronomii.'];
assert.match(planRXChat('O czym przed chwilą rozmawialiśmy?',historyWithRecall).answer,/Lubię astronomię/);
assert.doesNotMatch(planRXChat('O czym przed chwilą rozmawialiśmy?',historyWithRecall).answer,/Wcześniej napisałeś: „Przypomnij/);
assert.match(planRXChat('Przypomnij, o czym przed chwilą rozmawialiśmy.', ['Lubię astronomię.','Rozumiem.']).answer,/Lubię astronomię/);
console.log('RX BIBI name memory: 24/24 passed');
