import assert from 'node:assert/strict';
import {planRXChat} from '../rx-chat-planner.mjs';
const first='Cześć BIBI! Mam na imię Marek. Jak się dzisiaj czujesz?';
const answer1=planRXChat(first).answer;
assert.match(answer1,/Marek/);
assert.doesNotMatch(answer1,/Rozumiem, że chcesz porozmawiać o tym temacie/);
const second='BIBI, pamiętasz, jak mam na imię? Powiedz też, o czym przed chwilą rozmawialiśmy.';
const answer2=planRXChat(second,[first,answer1]).answer;
assert.match(answer2,/Marek/);
assert.match(answer2,/Wcześniej napisałeś/);
assert.match(planRXChat('Jak mam na imię?').answer,/Nie podałeś/);
assert.match(planRXChat('Co o mnie wiesz?', [first,answer1]).answer,/Marek/);
assert.match(planRXChat('Co wiesz o mnie?').answer,/Nie mam jeszcze/);
assert.doesNotMatch(planRXChat('Co o mnie wiesz?', [first,answer1]).answer,/mieszkasz|pracujesz|lat/);
const profile='Mieszkam w Krakowie. Interesuję się astronomią. Lubię książki.';
const profileAnswer=planRXChat('Co o mnie wiesz?', [first,answer1,profile,'Dzięki.']).answer;
assert.match(profileAnswer,/Krakowie/);
assert.match(profileAnswer,/astronomią/);
assert.doesNotMatch(profileAnswer,/Interesujesz się astronomią i lubię książki/);
assert.match(profileAnswer,/książki/);
assert.doesNotMatch(planRXChat('Co o mnie wiesz?').answer,/Krakowie|astronomią|książki/);
console.log('RX BIBI name memory: 12/12 passed');
