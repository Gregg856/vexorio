'use strict';
const assert=require('node:assert/strict');
const {summarize}=require('../rx-queen-ant-supervisor.cjs');
const ok=summarize({computer:{checks:[{file:'tests/ok.cjs',status:'passed'}]},ai:{kind:'rx-ant-ai-evaluation',candidateAccuracy:0.9,previousAccuracy:0.8},panel:{kind:'rx-queen-panel-check',ok:true}});
assert.equal(ok.state,'no_reported_failures');
assert.equal(ok.issues.length,0);
const bad=summarize({computer:{checks:[{file:'tests/fail.cjs',status:'failed'}]},ai:{kind:'rx-ant-ai-evaluation',candidateAccuracy:0.5,previousAccuracy:0.8},panel:{kind:'rx-queen-panel-check',ok:false}});
assert.equal(bad.issues.length,3);
assert.equal(bad.autoFixesApplied,0);
const browserBad=summarize({browser:{kind:'rx-queen-panel-browser',ok:false}});
assert.equal(browserBad.issues.length,1);
assert.equal(browserBad.issues[0].source,'browser');
assert.equal(summarize({browser:{kind:'rx-queen-panel-browser',ok:true}}).issues.length,0);
assert.throws(()=>summarize({browser:{kind:'wrong',ok:true}}),/Invalid browser/);
assert.throws(()=>summarize({ai:{kind:'wrong',candidateAccuracy:0.5}}),/Invalid AI/);
const media=summarize({studio:{kind:'rx-bibi-studio',ok:false},programs:{kind:'rx-programs-browser',ok:false}});
assert.equal(media.issues.length,2);
assert.equal(media.issues[0].source,'studio');
assert.equal(media.issues[1].source,'programs');
assert.equal(summarize({studio:{kind:'rx-bibi-studio',ok:true}}).issues.length,0);
assert.throws(()=>summarize({studio:{kind:'bad',ok:true}}),/Invalid studio/);
const fastOk=summarize({fast:{kind:'rx-fast-test-engine',results:[{file:'tests/ok.cjs',ok:true,ms:12}]}});
assert.equal(fastOk.state,'no_reported_failures');
assert.equal(fastOk.sourcesChecked.fast,true);
const fastBad=summarize({fast:{kind:'rx-fast-test-engine',results:[{file:'tests/slow.cjs',ok:false,timedOut:true,ms:20000},{file:'tests/fail.cjs',ok:false,timedOut:false,ms:30}]}});
assert.equal(fastBad.issues.length,2);
assert.equal(fastBad.issues[0].action,'inspect_test_timeout');
assert.equal(fastBad.issues[1].action,'inspect_failed_test');
assert.throws(()=>summarize({fast:{kind:'wrong',results:[]}}),/Invalid RX FAST/);
console.log('PASS RX QUEEN: cloud, AI and panel issue triage');
