'use strict';
const assert=require('node:assert/strict');
const {runCloudComputer,CHECKS}=require('../rx-mega-cloud-computer.cjs');
const r=runCloudComputer();
assert.equal(r.planned,CHECKS.length);
assert.equal(r.passed,0);
assert.equal(r.failed,0);
assert.equal(r.totalTestDurationMs,0);
assert.equal(r.cloudServerProvisioned,false);
assert.equal(r.labs.higgs.realCERNData,false);
assert.equal(r.labs.collider.physicalCollider,false);
assert.equal(r.labs.energy.energyProduced,false);
const executed=runCloudComputer({execute:true});
assert.equal(executed.failed,0,JSON.stringify(executed.checks));
assert.equal(executed.passed,CHECKS.length);
assert.ok(Number.isSafeInteger(executed.totalTestDurationMs)&&executed.totalTestDurationMs>=0);
assert.ok(executed.checks.every(x=>Number.isSafeInteger(x.durationMs)&&x.durationMs>=0));
const chosen=runCloudComputer({selectedChecks:[CHECKS[1],CHECKS[0]],maxChecks:1});
assert.deepEqual(chosen.checks.map(x=>x.file),[CHECKS[1]]);
assert.equal(chosen.deferred,1);
assert.equal(chosen.executed,0);
const one=runCloudComputer({execute:true,selectedChecks:[CHECKS[0]],maxChecks:1});
assert.equal(one.passed,1);
assert.equal(one.executed,1);
assert.equal(one.deferred,0);
assert.deepEqual(runCloudComputer({execute:true,maxChecks:0}).checks,[]);
assert.throws(()=>runCloudComputer({selectedChecks:['tests/unknown.cjs']}),/allowlisted/);
assert.throws(()=>runCloudComputer({selectedChecks:[CHECKS[0],CHECKS[0]]}),/duplicate/);
assert.throws(()=>runCloudComputer({maxChecks:-1}),/budget/);
assert.throws(()=>runCloudComputer({maxChecks:100}),/budget/);
console.log('PASS RX MEGA CLOUD COMPUTER bounded real test execution and lab reports');
