'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('guard-lab.html','utf8');
const categories=fs.readFileSync('guard-rx-categories.js','utf8');
const report=fs.readFileSync('guard-rx-monitor-report.js','utf8');
const chat=fs.readFileSync('guard-chat.js','utf8');
for(const id of ['guardPanelChat','guardChatMessages','guardChatForm','guardChatInput','guardRxMonitoringDetails','guardRxLiveReport','rxCategoryNav'])assert.ok(html.includes('id="'+id+'"'),'Missing RX element: '+id);
for(const id of ['guardTabChat','guardTabDeveloper','guardTabModeration'])assert.ok(html.includes('id="'+id+'"'),'Missing RX tab: '+id);
assert.ok(html.includes('/guard-rx-categories.js'),'RX category script missing');
assert.ok(html.includes('/guard-rx-monitor-report.js'),'RX report script missing');
assert.ok(html.includes('data-rx-history'),'RX monitoring history missing');
assert.ok(html.includes('data-rx-recurring'),'RX recurrence section missing');
assert.ok(html.includes('guard-rx-typing'),'Mobile chat mode missing');
assert.ok(html.includes('guardRxMonitoringDetails"><summary'),'Monitoring must be collapsible');
assert.ok(categories.includes("tab.click()"),'Category navigation does not open selected tab');
assert.ok(report.includes('runs.slice(0,5)'),'Five-run history missing');
assert.ok(chat.includes('openComposer();'),'Mobile conversation mode missing');
for(const [name,source] of [['categories',categories],['report',report],['chat',chat]])assert.doesNotThrow(()=>new vm.Script(source,{filename:name+'.js'}));
console.log('PASS: RX categories, mobile chat, monitoring history, and JavaScript syntax');
