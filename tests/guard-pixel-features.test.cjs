'use strict';
const assert=require('node:assert/strict');
const {extractPixelFeatures}=require('../guard/pixel-features.cjs');
const black=extractPixelFeatures({width:1,height:1,channels:3,data:Uint8Array.from([0,0,0])});
assert.deepEqual(black.meanRGB,[0,0,0]);
assert.equal(black.darkFraction,1);
assert.equal(black.brightFraction,0);
assert.equal(black.edgeContrast,0);
assert.equal(black.luminanceHistogram.reduce((a,b)=>a+b,0),1);
assert.equal(black.classification,'unknown');
assert.equal(black.requiresHumanReview,true);
const mixed=extractPixelFeatures({width:2,height:1,data:Uint8Array.from([0,0,0,255,255,255,255,255])});
assert.equal(mixed.darkFraction,0.5);
assert.equal(mixed.brightFraction,0.5);
assert.equal(mixed.edgeContrast,1);
assert.deepEqual(mixed.meanRGB,[0.5,0.5,0.5]);
assert.throws(()=>extractPixelFeatures({width:2,height:2,data:new Uint8Array(4)}),/Invalid pixel buffer/);
assert.throws(()=>extractPixelFeatures({width:12000,height:12000,data:new Uint8Array(0)}),/Pixel limit exceeded/);
console.log('PASS: Guard decoded-pixel features and bounded local extraction');
