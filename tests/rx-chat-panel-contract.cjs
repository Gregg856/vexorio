'use strict';
// Non-credentialed automated RX panel-to-chat contract smoke test.
// Does not impersonate an administrator or send a private token.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('rx-admin-prototype.html','utf8');
const worker=fs.readFileSync('worker.js','utf8');
assert.match(html,/fetch\('\/api\/rx\/chat',\{method:'POST'/);
assert.match(html,/Authorization:'Bearer '\+token/);
assert.match(html,/rxClient\.auth\.getSession\(\)/);
assert.match(html,/async function answerServerBrainChat\(question\)/);
assert.match(worker,/url\.pathname==='\/api\/rx\/chat'/);
assert.match(worker,/request\.method!=='POST'/);
assert.match(worker,/request\.headers\.get\('Origin'\)!==url\.origin/);
assert.match(worker,/rpc\/is_vexorio_admin/);
assert.match(worker,/planRXChat\(message,history,bibiLearning\)/);
assert.match(worker,/RX_BIBI_LEARNING_TOKEN/);
assert.match(worker,/RX_BIBI_LEARNING_URL/);
// BIBI verifies the actual owner-only Queen -> RX Developer dispatch contract.
assert.match(worker,/developerMatch/);
const developerLine=worker.split('\n').find(line=>line.includes('const developerMatch='));
assert.ok(developerLine,'Missing RX Developer command matcher');
assert.ok(!developerLine.includes('\\\\s'),'RX Developer command must recognize spaces, not literal backslashes');
assert.ok(developerLine.includes('\\s+'),'RX Developer command must match whitespace');
assert.match(worker,/rx-developer-bridge\.yml\/dispatches/);
assert.match(worker,/RX_GITHUB_DISPATCH_TOKEN/);
assert.match(worker,/identity\.id!==env\.RX_ADMIN_USER_ID/);
assert.match(worker,/inputs:\{target\}/);
assert.match(worker,/queued:true,executed:1/);
const workflow=fs.readFileSync('.github/workflows/rx-developer-bridge.yml','utf8');
const runner=fs.readFileSync('rx-developer-review-runner.cjs','utf8');
assert.match(workflow,/RX_TARGET/);
assert.match(workflow,/node rx-developer-review-runner\.cjs/);
assert.match(workflow,/node tests\/rx-developer-bridge-isolated\.cjs/);
assert.match(runner,/inspectAndPropose/);
assert.match(runner,/rx-developer-review\.json/);
assert.match(runner,/changesApplied:false/);
assert.match(worker,/engine:localEngine/);
assert.match(html,/data\.answer/);
// RX BIBI: validate the actual chat composer and server route guardrails.
assert.match(html,/<form[^>]*class="composer"[^>]*id="form"/);
assert.match(html,/<textarea[^>]*id="input"[^>]*maxlength="8000"/);
assert.match(html,/<button[^>]*class="send"[^>]*type="submit">Wyślij<\/button>/);
assert.match(html,/getElementById\('form'\)\.addEventListener\('submit'/);
assert.match(html,/e\.preventDefault\(\)/);
assert.match(html,/input\.value\.trim\(\)/);
assert.match(html,/input\.value=''/);
assert.match(worker,/planRXChat\(message,history,bibiLearning\)/);
// RX Queen handoff regression: no unsupported browser inbox write.
const queenPanel=fs.readFileSync('guard-rx-queen-panel.js','utf8');
const cloudComputer=fs.readFileSync('rx-mega-cloud-computer.cjs','utf8');
assert.ok(!queenPanel.includes("fetch('/api/rx/inbox'"),'Queen must not POST to unsupported inbox');
// Queen now dispatches approved commands through the existing authenticated coordinator endpoint.
assert.match(queenPanel,/fetch\('\/api\/rx\/coordinator\/run'/);
assert.match(queenPanel,/client\.auth\.getSession\(\)/);
assert.match(queenPanel,/Authorization':'Bearer '/);
assert.match(queenPanel,/JSON\.stringify\(\{command:approved\.description\}\)/);
assert.match(worker,/url\.pathname === '\/api\/rx\/coordinator\/run'/);
assert.match(worker,/identity\.id!==env\.RX_ADMIN_USER_ID/);
assert.match(worker,/rx-coordinator-cloud\.yml/);
assert.match(worker,/rpc\/is_vexorio_admin/);
assert.ok(cloudComputer.includes('function runQueenApprovedChecks('),'Queen executor bridge missing');
assert.match(cloudComputer,/approved&&execute/);
const {runQueenApprovedChecks}=require('../rx-mega-cloud-computer.cjs');
const plan={kind:'rx-ordered-work-proposal',requiresApproval:true,executed:false,stages:[{module:'RX BIBI',action:'Sprawdź czat'},{module:'RX Developer',action:'Przygotuj poprawkę'}]};
const blocked=runQueenApprovedChecks(plan,{approved:false,execute:true});
assert.equal(blocked.executed,0);
assert.equal(blocked.productionModified,false);
const preview=runQueenApprovedChecks(plan,{approved:true,execute:false});
assert.equal(preview.executed,0);
assert.throws(()=>runQueenApprovedChecks({...plan,stages:[{module:'unknown',action:'run arbitrary'}]},{approved:true,execute:true}),/allowlisted/);
console.log('RX chat panel/server contract OK (without authenticated session)');
