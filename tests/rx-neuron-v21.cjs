'use strict';
const assert=require('node:assert/strict');
const {createRXHearts}=require('../rx-million-hearts.js');
const {compareRepairSuggestions}=require('../rx-neuron-v21.js');
const rx=createRXHearts();
const input={cell:'tests',errorCode:'overflow'};
rx.rememberFailure('tests','overflow');
rx.rememberVerifiedFix('tests','overflow','fix_a',{testsPassed:true});
const sample=fix=>[{input,expectedFixId:fix,approvedForTraining:true}];
const same=compareRepairSuggestions(rx,sample('fix_a'),input);
assert.equal(same.status,'agreement');
assert.equal(same.suggestedFixId,'fix_a');
assert.equal(same.canAutoApply,false);
const conflict=compareRepairSuggestions(rx,sample('fix_b'),input);
assert.equal(conflict.status,'conflict');
assert.equal(conflict.suggestedFixId,null);
assert.equal(compareRepairSuggestions(rx,sample('fix_a'),{cell:'tests',errorCode:'other'}).status,'unknown');
assert.throws(()=>compareRepairSuggestions(rx,[{...sample('fix_a')[0],approvedForTraining:false}],input),/not approved/);
console.log('RX NEURON 2.1: PASS');
