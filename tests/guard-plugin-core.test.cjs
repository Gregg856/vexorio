'use strict';
const assert=require('node:assert/strict');
const {createRegistry}=require('../guard/plugin-core.cjs');
(async()=>{
 const registry=createRegistry();
 registry.register({id:'task-summary',description:'Local task summary',permissions:['read:task'],run:({task})=>({message:'Zadanie: '+task})});
 assert.deepEqual(registry.recommend('task summary').map(item=>item.id),['task-summary']);
 assert.equal(registry.recommend('unrelated words').length,0);
 assert.throws(()=>registry.recommend('task summary','write:production'),/Invalid recommendation/);
 assert.equal(registry.recommend('task summary')[0].requiresApproval,true);
 const confident=registry.recommendForModel({},()=>({label:'general',confidence:0.95,needsReview:false}),'task summary');
 assert.deepEqual(confident.candidates.map(item=>item.id),['task-summary']);
 assert.equal(confident.canExecuteAutomatically,false);
 const uncertain=registry.recommendForModel({},()=>({label:'general',confidence:0.3,needsReview:true}),'task summary');
 assert.equal(uncertain.candidates.length,0);
 assert.equal(uncertain.needsReview,true);
 assert.equal(registry.list()[0].id,'task-summary');
 assert.equal(registry.list()[0].permissions[0],'read:task');
 assert.throws(()=>registry.register({id:'task-summary',permissions:[],run:()=>({message:'x'})}),/Invalid or duplicate/);
 assert.throws(()=>registry.register({id:'unsafe-plugin',permissions:['write:production'],run:()=>({message:'x'})}),/Permission denied/);
 await assert.rejects(()=>registry.execute('task-summary',{task:'Test'}),/approval required/);
 assert.deepEqual(await registry.execute('task-summary',{task:'Test'},true),{plugin:'task-summary',message:'Zadanie: Test'});
 await assert.rejects(()=>registry.execute('missing',{task:'Test'},true),/Unknown plugin/);
 registry.register({id:'broken-plugin',description:'broken diagnostics',permissions:['read:task'],run:()=>{throw Error('Private error detail');}});
 assert.equal(registry.recommend('broken diagnostics').length,1);
 await assert.rejects(()=>registry.execute('broken-plugin',{task:'diagnostics'},true),/Private error detail/);
 assert.equal(registry.recommend('broken diagnostics').length,0);
 const failed=registry.diagnostics().find(item=>item.id==='broken-plugin');
 assert.equal(failed.status,'error');
 assert.equal(failed.failures,1);
 assert.equal(failed.lastError.includes('Private error detail'),false);
 assert.throws(()=>registry.resetHealth('broken-plugin'),/approval required/);
 const reset=registry.resetHealth('broken-plugin',true);
 assert.equal(reset.requiresVerification,true);
 assert.equal(reset.failures,1);
 assert.equal(registry.diagnostics().find(item=>item.id==='broken-plugin').failures,1);
 assert.equal(registry.recommend('broken diagnostics').length,1);
 console.log('PASS: Strażak Plugin Core permissions, registry and approval');
})().catch(e=>{console.error(e);process.exitCode=1;});
