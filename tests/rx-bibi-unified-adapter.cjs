'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {reviewBibiReports} = require('../rx-bibi-unified-adapter.cjs');
const dir = fs.mkdtempSync(path.join(os.tmpdir(),'rx-unified-'));
const reportPath = path.join(dir,'rx-queen-ant-supervisor.json');
const report = {kind:'rx-queen-ant-supervisor',issues:[{source:'fast',action:'inspect_failed_test',target:'src/example.js',priority:'high'}]};
try {
  fs.writeFileSync(reportPath,JSON.stringify(report));
  const result = reviewBibiReports({dir,runId:'ci_1'});
  assert.equal(result.summary.tasks,1);
  assert.equal(result.reviewQueue.tasks.length,1);
  assert.equal(result.reviewQueue.tasks[0].approved,false);
  assert.equal(result.reviewQueue.tasks[0].executed,false);
  assert.equal(result.summary.signals,1);
  assert.equal(result.productionModified,false);
  assert.equal(result.requiresApproval,true);
  assert.equal(result.autoFixesApplied,0);
  assert.equal(result.summary.analyzed,0);
  assert.throws(()=>reviewBibiReports({dir,runId:'../bad'}),/Invalid RX run ID/);
  const srcDir=path.join(dir,'src');
  fs.mkdirSync(srcDir);
  const srcPath=path.join(srcDir,'example.js');
  fs.writeFileSync(srcPath,'const safe = 1;\n');
  const reviewed=reviewBibiReports({dir,runId:'ci_3',root:dir,loadLocalSources:true});
  assert.equal(reviewed.summary.analyzed,1);
  assert.equal(reviewed.developerQueue.kind,'rx-queen-developer-review-queue');
  assert.equal(reviewed.developerQueue.reviews[0].approved,false);
  assert.equal(reviewed.developerQueue.reviews[0].executed,false);
  assert.equal(reviewed.developerQueue.automaticDeployment,false);
  assert.equal(reviewed.reviews[0].suggestions.length,0);
  assert.equal(reviewed.sourceLoad.loaded,1);
  assert.equal(fs.readFileSync(srcPath,'utf8'),'const safe = 1;\n');
  fs.writeFileSync(srcPath,'debugger;\n');
  const proposed=reviewBibiReports({dir,runId:'ci_propose',root:dir,loadLocalSources:true});
  assert.equal(proposed.reviews.length,1);
  assert.equal(proposed.reviews[0].suggestions.length,1);
  assert.equal(proposed.reviews[0].suggestions[0].status,'review_only');
  assert.equal(fs.readFileSync(srcPath,'utf8'),'debugger;\n');
  fs.rmSync(srcPath);
  fs.symlinkSync(path.join(os.tmpdir(),'rx-unified-outside.js'),srcPath);
  const skipped=reviewBibiReports({dir,runId:'ci_4',root:dir,loadLocalSources:true});
  assert.equal(skipped.summary.analyzed,0);
  assert.equal(skipped.sourceLoad.loaded,0);
  fs.rmSync(srcPath);
  fs.writeFileSync(reportPath,'{');
  assert.throws(()=>reviewBibiReports({dir,runId:'ci_2'}),SyntaxError);
  fs.writeFileSync(reportPath,'x'.repeat(2000001));
  assert.throws(()=>reviewBibiReports({dir,runId:'ci_5'}),/Invalid RX report size\/type/);
  console.log('PASS RX BIBI Unified Adapter (read-only, malformed, oversize, symlink, run ID)');
} finally { fs.rmSync(dir,{recursive:true,force:true}); }
