'use strict';
const assert=require('node:assert/strict');
const {createTaskQueue}=require('../guard-task-queue.js');
const queue=createTaskQueue();
const t=queue.add('Sprawdź filtry');
assert.deepEqual(t,{id:1,title:'Sprawdź filtry',status:'pending'});
assert.equal(queue.complete(1),null);
assert.equal(queue.approve(1).status,'approved');
assert.equal(queue.approve(1),null);
assert.equal(queue.complete(1).status,'completed');
assert.equal(queue.cancel(1),null);
const t2=queue.add('Zbadaj błąd');
assert.equal(queue.cancel(t2.id).status,'cancelled');
assert.equal(queue.approve(t2.id),null);
assert.equal(queue.list().length,2);
assert.throws(()=>queue.add(''),/Invalid task/);
assert.throws(()=>queue.add('x'.repeat(501)),/Invalid task/);
assert.equal(createTaskQueue().list().length,0);
console.log('PASS: Guard queue requires explicit approval and prevents invalid transitions');
