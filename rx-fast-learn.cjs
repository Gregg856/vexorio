'use strict';
// RX FAST LEARN: bounded supervised intent training; not a generative language model.
const {createNetwork,train,forward}=require('./rx-neural-core.cjs');
const {toFrequencyVector}=require('./rx-language-tokenizer.cjs');
const LABELS=Object.freeze(['greeting','math','knowledge','translation']);
const EXAMPLES=Object.freeze([
 ['cześć','greeting'],['hej','greeting'],['witaj','greeting'],['dzień dobry','greeting'],
 ['policz 5 plus 4','math'],['oblicz 7 razy 8','math'],['ile to 3 plus 2','math'],['oblicz 12 minus 4','math'],
 ['co to jest atom','knowledge'],['czym jest fotosynteza','knowledge'],['kim jest Kopernik','knowledge'],['gdzie leży Berlin','knowledge'],
 ['przetłumacz słowo','translation'],['translate pl to de','translation'],['tłumaczenie na niemiecki','translation'],['przetlumacz na angielski','translation']
]);
function vector(text){if(typeof text!=='string'||!text.trim()||text.length>160)throw Error('Invalid text');return toFrequencyVector(text.toLocaleLowerCase('pl-PL'));}
function fit({epochs=180}={}){
 if(!Number.isSafeInteger(epochs)||epochs<1||epochs>1000)throw Error('Invalid epochs');
 const net=createNetwork(256,32,LABELS.length);
 const x=new Float32Array(EXAMPLES.length*256),y=new Float32Array(EXAMPLES.length*LABELS.length);
 EXAMPLES.forEach(([sentence,label],i)=>{x.set(vector(sentence),i*256);y[i*LABELS.length+LABELS.indexOf(label)]=1;});
 const metrics=train(net,x,y,{epochs,rate:0.08});
 return {net,metrics,trainingCount:EXAMPLES.length};
}
function classify(net,text){
 const scores=Array.from(forward(net,vector(text)).pred);
 const index=scores.indexOf(Math.max(...scores));
 return {intent:LABELS[index],score:scores[index]};
}
// Bounded character-level next-token experiment. Deterministic decoding, no network.
const {tokenize,detokenize}=require('./rx-language-tokenizer.cjs');
function trainText({sentences=['cześć, jak mogę pomóc?','dzień dobry, w czym pomóc?','chętnie pomogę ci znaleźć informacje.'],epochs=90}={}){
 if(!Array.isArray(sentences)||sentences.length<2||sentences.length>40||sentences.some(t=>typeof t!=='string'||!t.trim()||t.length>120)||!Number.isSafeInteger(epochs)||epochs<1||epochs>500)throw Error('Invalid training corpus');
 const pairs=[];
 for(const sentence of sentences){
  const ids=tokenize(sentence,{boundary:false}).ids;
  for(let i=0;i<ids.length-1;i++)pairs.push([ids[i],ids[i+1]]);
 }
 if(pairs.length>3000||pairs.length<2)throw Error('Invalid training size');
 const net=createNetwork(256,48,256);
 const x=new Float32Array(pairs.length*256),y=new Float32Array(pairs.length*256);
 pairs.forEach(([a,b],i)=>{x[i*256+a]=1;y[i*256+b]=1;});
 const metrics=train(net,x,y,{epochs,rate:0.035});
 return {net,metrics,pairs:pairs.length};
}
function generateText(net,{seed='c',maxBytes=40}={}){
 if(typeof seed!=='string'||!seed||seed.length>80||!Number.isSafeInteger(maxBytes)||maxBytes<1||maxBytes>120)throw Error('Invalid generation request');
 const ids=tokenize(seed,{boundary:false}).ids;
 const output=[...ids];
 for(let i=0;i<maxBytes;i++){
  const input=new Float32Array(256);input[output[output.length-1]]=1;
  const scores=forward(net,input).pred;
  let best=32;
  for(let j=0;j<256;j++)if(scores[j]>scores[best])best=j;
  output.push(best);
 }
 // Generated bytes may end in the middle of UTF-8; keep valid prefix only.
 while(output.length>ids.length){try{return detokenize(output);}catch{output.pop();}}
 return seed;
}
module.exports={EXAMPLES,LABELS,fit,classify,vector,trainText,generateText};

